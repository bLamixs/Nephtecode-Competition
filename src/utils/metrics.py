"""
Модуль: src/utils/metrics.py
Назначение: Расчёт статистических метрик точности моделей прогнозирования качества (ВАК и ML).

Контекст задачи:
В задаче оценки качества нефтепродуктов (содержание серы, плотность D15, фракционный состав T50/T90/T95)
критически важны не только средние ошибки, но и систематическое смещение (bias):
- Положительный bias по сере означает систематическое завышение (ложные тревоги).
- Отрицательный bias по сере крайне опасен, так как модель может пропустить реальное превышение нормы 10 мг/кг.

Валидация должна производиться строго на отложенной по времени выборке (Holdout/Time-split),
исключая заглядывание в будущее.
"""

import numpy as np
from typing import Dict


def calc_regression_metrics(y_true: np.ndarray, y_pred: np.ndarray) -> Dict[str, float]:
    """
    Вычисляет основные метрики регрессии с фильтрацией пропусков (NaN):
    - MAE (Mean Absolute Error): средняя абсолютная ошибка.
    - RMSE (Root Mean Squared Error): среднеквадратичная ошибка (чувствительна к крупным выбросам).
    - Bias (Mean Error): среднее систематическое отклонение (y_pred - y_true).
    - Count: количество валидных пар измерений.

    Параметры:
        y_true (np.ndarray): Фактические значения качества (из ЛИМС или ПАК).
        y_pred (np.ndarray): Прогнозные значения (ВАК, ML или ансамбль).

    Возвращает:
        Dict[str, float]: Словарь с округлёнными до 4 знаков значениями метрик.
    """
    # Создаем булеву маску для отбора только тех временных меток, где есть и факт, и прогноз
    valid_mask = ~np.isnan(y_true) & ~np.isnan(y_pred)
    y_t = y_true[valid_mask]
    y_p = y_pred[valid_mask]

    # Если пересечений нет (например, отсутствие лабораторных замеров в окне)
    if len(y_t) == 0:
        return {"mae": 0.0, "rmse": 0.0, "bias": 0.0, "count": 0}
    
    diff = y_p - y_t
    mae = float(np.mean(np.abs(diff)))
    rmse = float(np.sqrt(np.mean(diff ** 2)))
    bias = float(np.mean(diff))
    
    return {
        "mae": round(mae, 4),
        "rmse": round(rmse, 4),
        "bias": round(bias, 4),
        "count": int(len(y_t))
    }
