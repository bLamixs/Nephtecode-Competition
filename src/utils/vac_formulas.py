"""
Модуль: src/utils/vac_formulas.py
Назначение: Библиотека формул Виртуальных Анализаторов Качества (ВАК).

Контекст и технологическое обоснование:
Виртуальные анализаторы качества — это детерминированные эмпирические и технологические
модели, связывающие режимные параметры КИП (температуры, давления, расходы, уровни)
с физико-химическими показателями качества продуктов разделения и гидроочистки.

В мультиагентной системе ВАК выполняет роль базовой модели (Baseline):
1. Быстрый расчёт в реальном времени даже при отсутствии свежих лабораторных замеров ЛИМС.
2. Использование в качестве опорного сигнала: Quality Agent обучает ML-модели (LightGBM/Ridge)
   на остатках (Residuals = LIMS - VAC), что обеспечивает физическую устойчивость прогноза
   и устойчивость к переобучению.

Источники формул: Официальное техническое задание хакатона «НефтеКод».
"""

import numpy as np
import pandas as pd
from typing import Dict, Any, Optional


class VirtualAnalyzers:
    """
    Класс-коллекция статических методов для расчёта аналитических формул ВАК
    установок АВТ-6 и гидроочистки дизельного топлива 24-2000.
    """

    # =========================================================================
    # БЛОК 1: ВАК УСТАНОВКИ АВТ-6 (АТМОСФЕРНО-ВАКУУМНАЯ ТРУБЧАТАЯ)
    # =========================================================================

    @staticmethod
    def calc_avt6_240_350_d15(row: Dict[str, float]) -> Optional[float]:
        """
        ВАК: Расчёт плотности при 15°C фракции 240-350°C (дизельная фракция АВТ).
        Формула: 791.22872 - 5.30294 * (F30 / (F32 + F30)) + 0.52755 * T66 - 0.15629 * T33
        
        Параметры входа:
            F30, F32: расходы компонентов/орошения.
            T66: температура низа/отбора.
            T33: температура ввода сырья/верха.
        """
        denom = row.get('F32', 0.0) + row.get('F30', 0.0)
        if denom == 0:
            return None  # Защита от деления на ноль при остановках или нулевых расходах
        return 791.22872 - 5.30294 * (row.get('F30', 0.0) / denom) + 0.52755 * row.get('T66', 0.0) - 0.15629 * row.get('T33', 0.0)

    @staticmethod
    def calc_avt6_240_350_t50(row: Dict[str, float]) -> float:
        """
        ВАК: Температура выкипания 50% фракции 240-350°C.
        Отражает среднюю температуру кипения и фракционную загрузку атмосферной колонны.
        Формула: 283.177 + F7*(-0.01685) + 0.06248*F30 + 0.22048*F34 - 0.25816*F45 - 0.12159*F59 + 0.01221*F63
        """
        return (283.177 - 0.01685 * row.get('F7', 0.0) + 0.06248 * row.get('F30', 0.0) +
                0.22048 * row.get('F34', 0.0) - 0.25816 * row.get('F45', 0.0) -
                0.12159 * row.get('F59', 0.0) + 0.01221 * row.get('F63', 0.0))

    @staticmethod
    def calc_avt6_240_350_ebp(row: Dict[str, float]) -> float:
        """
        ВАК: Конец кипения (EBP - End Boiling Point) дизельной фракции 240-350°C.
        Критически важен для исключения попадания тяжёлых хвостовых фракций в дизельное топливо.
        Формула: 813.883 + 2.66463*F30 - 0.20239*T33 - 3.65888*F36 - 14.08235*T37 - 1.32603*T40 + 14.60206*T58
        """
        return (813.883 + 2.66463 * row.get('F30', 0.0) - 0.20239 * row.get('T33', 0.0) -
                3.65888 * row.get('F36', 0.0) - 14.08235 * row.get('T37', 0.0) -
                1.32603 * row.get('T40', 0.0) + 14.60206 * row.get('T58', 0.0))

    @staticmethod
    def calc_avt6_240_350_cfpp(row: Dict[str, float]) -> Optional[float]:
        """
        ВАК: Предельная температура фильтруемости (CFPP / ПТФ) фракции 240-350°C.
        Определяет низкотемпературные свойства дизельного топлива.
        Формула: 31.40363 - 0.06784*T33 + 17.411*P67 - 8.11544*P4 - 0.47309*(F65/(F32+F30))
        """
        denom = row.get('F32', 0.0) + row.get('F30', 0.0)
        if denom == 0:
            return None
        return (31.40363 - 0.06784 * row.get('T33', 0.0) + 17.411 * row.get('P67', 0.0) -
                8.11544 * row.get('P4', 0.0) - 0.47309 * (row.get('F65', 0.0) / denom))

    @staticmethod
    def calc_avt6_350_t50(row: Dict[str, float]) -> Optional[float]:
        """
        ВАК: Температура 50% выкипания фракции >350°C (вакуумный газойль / остаток).
        Формула: 981.06539 + 0.27467*T42 - 0.32983*(F31/F57) - 0.49014*T48
        """
        f57 = row.get('F57', 0.0)
        if f57 == 0:
            return None
        return 981.06539 + 0.27467 * row.get('T42', 0.0) - 0.32983 * (row.get('F31', 0.0) / f57) - 0.49014 * row.get('T48', 0.0)

    @staticmethod
    def calc_avt6_350_i350(row: Dict[str, float]) -> float:
        """
        ВАК: Доля фракции до 350°C в остатке колонны.
        Формула: 39.562 - 1.62865*L43 - 0.76664*T6 - 0.22361*T18 + 0.00031*F64*(T15-T11)
        """
        return (39.562 - 1.62865 * row.get('L43', 0.0) - 0.76664 * row.get('T6', 0.0) -
                0.22361 * row.get('T18', 0.0) + 0.00031 * row.get('F64', 0.0) * (row.get('T15', 0.0) - row.get('T11', 0.0)))

    @staticmethod
    def calc_avt6_350_d15(row: Dict[str, float]) -> Optional[float]:
        """
        ВАК: Плотность при 15°C фракции >350°C.
        Формула: 983.092 + 0.27467*T42 - 0.49014*T48 - 0.32983*(F31/F57)
        """
        f57 = row.get('F57', 0.0)
        if f57 == 0:
            return None
        return 983.092 + 0.27467 * row.get('T42', 0.0) - 0.49014 * row.get('T48', 0.0) - 0.32983 * (row.get('F31', 0.0) / f57)

    @staticmethod
    def calc_avt6_350_500_viscosity(row: Dict[str, float]) -> float:
        """
        ВАК: Кинематическая вязкость вакуумного дистиллята 350-500°C.
        Формула: 5.831 + 0.00976*T6 + 0.01188*T13 + 0.00224*T18 + 0.01905*T20 + 0.00794*L43 -
                 0.02496*T48 - 0.00008*P50 - 0.00882*F53 - 0.00394*P51 - 0.00255*F59 + 0.01153*T61
        """
        return (5.831 + 0.00976 * row.get('T6', 0.0) + 0.01188 * row.get('T13', 0.0) +
                0.00224 * row.get('T18', 0.0) + 0.01905 * row.get('T20', 0.0) +
                0.00794 * row.get('L43', 0.0) - 0.02496 * row.get('T48', 0.0) -
                0.00008 * row.get('P50', 0.0) - 0.00882 * row.get('F53', 0.0) -
                0.00394 * row.get('P51', 0.0) - 0.00255 * row.get('F59', 0.0) +
                0.01153 * row.get('T61', 0.0))

    @staticmethod
    def calc_avt6_350_cfpp(row: Dict[str, float]) -> Optional[float]:
        """
        ВАК: Предельная температура фильтруемости (CFPP) фракции >350°C.
        Формула: 19.27111 - 0.10582*T48 + 0.13836*T40 - 0.42304*(F31/F57)
        """
        f57 = row.get('F57', 0.0)
        if f57 == 0:
            return None
        return 19.27111 - 0.10582 * row.get('T48', 0.0) + 0.13836 * row.get('T40', 0.0) - 0.42304 * (row.get('F31', 0.0) / f57)

    # =========================================================================
    # БЛОК 2: ВАК УСТАНОВКИ ГИДРООЧИСТКИ 24-2000 (ГОДТ - ГИДРООЧИЩЕННОЕ ДТ)
    # =========================================================================

    @staticmethod
    def calc_godt_t90(row: Dict[str, float]) -> Optional[float]:
        """
        ВАК: Температура выкипания 90% гидроочищенного дизельного топлива (ГОДТ).
        Формула: 162.998 + 0.12945*T12 + 59.57*F15 + 0.00036*W7 + T23*0.26366 - 424.72638*(F1/F26)
        """
        f26 = row.get('F26', 0.0)
        if f26 == 0:
            return None
        return (162.998 + 0.12945 * row.get('T12', 0.0) + 59.57 * row.get('F15', 0.0) +
                0.00036 * row.get('W7', 0.0) + 0.26366 * row.get('T23', 0.0) -
                424.72638 * (row.get('F1', 0.0) / f26))

    @staticmethod
    def calc_godt_t50(row: Dict[str, float]) -> float:
        """
        ВАК: Температура выкипания 50% гидроочищенного дизельного топлива.
        Формула: 44.625 + 10.0224*P13 + 0.06981*F9 + 0.8052*T6
        """
        return 44.625 + 10.0224 * row.get('P13', 0.0) + 0.06981 * row.get('F9', 0.0) + 0.8052 * row.get('T6', 0.0)

    @staticmethod
    def calc_godt_i250(row: Dict[str, float]) -> float:
        """
        ВАК: Выход фракции до 250°C в гидроочищенном дизельном топливе.
        Формула: 84.585 - 0.21172*T5 + 0.12137*T11 - 0.00014*F25 + 0.56248*F14 - 0.16317*T23 + 0.20272*T16
        """
        return (84.585 - 0.21172 * row.get('T5', 0.0) + 0.12137 * row.get('T11', 0.0) -
                0.00014 * row.get('F25', 0.0) + 0.56248 * row.get('F14', 0.0) -
                0.16317 * row.get('T23', 0.0) + 0.20272 * row.get('T16', 0.0))

    @staticmethod
    def calc_godt_d15(row: Dict[str, float], d15_lims: float = 835.0) -> float:
        """
        ВАК: Плотность при 15°C гидроочищенного дизельного топлива.
        Гибридная формула, учитывающая последний лабораторный замер плотности LIMS.
        Формула: 667.881 + 0.15417*D15_lims + 0.00005*F22 + 0.10774*T11
        """
        return 667.881 + 0.15417 * d15_lims + 0.00005 * row.get('F22', 0.0) + 0.10774 * row.get('T11', 0.0)

    @staticmethod
    def calc_godt_cloud_point(row: Dict[str, float]) -> float:
        """
        ВАК: Температура помутнения (Cloud Point) ГОДТ.
        Формула: F22 + 0.0021*W7 + 0.00008*F25 - 0.30656*F1 + 0.12018*T6 + 0.01916*F9 - 48.254 - 0.05249*T16 + 0.00011
        """
        return (row.get('F22', 0.0) + 0.0021 * row.get('W7', 0.0) + 0.00008 * row.get('F25', 0.0) -
                0.30656 * row.get('F1', 0.0) + 0.12018 * row.get('T6', 0.0) + 0.01916 * row.get('F9', 0.0) -
                48.254 - 0.05249 * row.get('T16', 0.0) + 0.00011)

    @staticmethod
    def calc_godt_t95(row: Dict[str, float], t95_lims: float = 350.0) -> float:
        """
        ВАК: Температура выкипания 95% ГОДТ (жёсткий предел по ГОСТ для ЕВРО-5).
        Формула: 0.03814*F9 - 9.201 - 0.00002*F2 + 0.62259*T6 + 0.48321*T95_lims
        """
        return (0.03814 * row.get('F9', 0.0) - 9.201 - 0.00002 * row.get('F2', 0.0) +
                0.62259 * row.get('T6', 0.0) + 0.48321 * t95_lims)

    @staticmethod
    def calc_godt_cfpp(row: Dict[str, float]) -> float:
        """
        ВАК: Предельная температура фильтруемости (CFPP) гидроочищенного дизельного топлива.
        Формула: 0.22088*T6 - 102.375 - 47.75834*P8 + 0.03862*F9 + 43.60207*W7 + 43.81849*P24
        """
        return (0.22088 * row.get('T6', 0.0) - 102.375 - 47.75834 * row.get('P8', 0.0) +
                0.03862 * row.get('F9', 0.0) + 43.60207 * row.get('W7', 0.0) + 43.81849 * row.get('P24', 0.0))

    @staticmethod
    def calc_godt_ibp(row: Dict[str, float]) -> float:
        """
        ВАК: Начало кипения (IBP - Initial Boiling Point) ГОДТ.
        Влияет на температуру вспышки в закрытом тигле (Flash Point).
        Формула: 137.762 - 0.0653*F26 + 0.00011*F22 + 5.78137*P13 - 34.58028*P24 -
                 0.00993*F14 - 0.99962*W4 + 0.32232*T23 - 0.09406*T16
        """
        return (137.762 - 0.0653 * row.get('F26', 0.0) + 0.00011 * row.get('F22', 0.0) +
                5.78137 * row.get('P13', 0.0) - 34.58028 * row.get('P24', 0.0) -
                0.00993 * row.get('F14', 0.0) - 0.99962 * row.get('W4', 0.0) +
                0.32232 * row.get('T23', 0.0) - 0.09406 * row.get('T16', 0.0))
